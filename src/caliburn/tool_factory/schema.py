"""Immutable unapproved artifacts and fenced proposal receipts, separate from activation."""

from sqlalchemy import (
    JSON,
    CheckConstraint,
    Column,
    Float,
    ForeignKey,
    Integer,
    String,
    Table,
    UniqueConstraint,
)

from caliburn.policy.schema import metadata

bundles = Table(
    "factory_bundles",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("origin_task_id", ForeignKey("runtime_tasks.id"), nullable=False),
    Column("origin_step_id", ForeignKey("runtime_steps.id"), nullable=False, unique=True),
    Column("actor", String(100), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("creator_role", String(100), nullable=False),
    Column("name", String(64), nullable=False),
    Column("version", String(30), nullable=False),
    Column("kind", String(10), nullable=False),
    Column("state", String(20), nullable=False),
    Column("sha256", String(64), nullable=False),
    Column("payload", JSON, nullable=False),
    Column("checks", JSON, nullable=False),
    Column("created_at", Float, nullable=False),
    CheckConstraint("state = 'QUARANTINED'", name="ck_factory_quarantine_only"),
    UniqueConstraint("actor", "tenant", "name", "version", name="uq_factory_version"),
)
proposals = Table(
    "factory_proposals",
    metadata,
    Column("step_id", ForeignKey("runtime_steps.id"), primary_key=True),
    Column("task_id", ForeignKey("runtime_tasks.id"), nullable=False),
    Column("bundle_id", ForeignKey(bundles.c.id), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("gap", String(2000), nullable=False),
    Column("request_sha256", String(64), nullable=False),
    Column("created_at", Float, nullable=False),
)

verifiers = Table(
    "factory_verifiers",
    metadata,
    Column("db_role", String(63), primary_key=True),
    Column("principal", String(80), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("enabled", String(3), nullable=False),
)
check_jobs = Table(
    "factory_check_jobs",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("task_id", ForeignKey("runtime_tasks.id"), nullable=False),
    Column("step_id", ForeignKey("runtime_steps.id"), nullable=False, unique=True),
    Column("bundle_id", ForeignKey(bundles.c.id), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("creator_role", String(100), nullable=False),
    Column("bundle_sha256", String(64), nullable=False),
    Column("checker_sha256", String(64), nullable=False),
    Column("state", String(20), nullable=False),
    Column("created_at", Float, nullable=False),
    Column("deadline", Float, nullable=False),
    Column("attempts", Integer, nullable=False, default=0),
    Column("lease_token", String(36)),
    Column("lease_until", Float),
    Column("error", String(50)),
)
check_reports = Table(
    "factory_check_reports",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("job_id", ForeignKey(check_jobs.c.id), nullable=False, unique=True),
    Column("lease_token", String(36), nullable=False),
    Column("verifier_role", String(63), nullable=False),
    Column("body", JSON, nullable=False),
    Column("body_sha256", String(64), nullable=False),
    Column("created_at", Float, nullable=False),
)

exec_roles = Table(
    "factory_exec_roles",
    metadata,
    Column("db_role", String(63), primary_key=True),
    Column("principal", String(80), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("kind", String(10), nullable=False),
    Column("enabled", String(3), nullable=False),
)
exec_plans = Table(
    "factory_exec_plans",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("bundle_id", ForeignKey(bundles.c.id), nullable=False),
    Column("report_id", ForeignKey(check_reports.c.id), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("owner_role", String(100), nullable=False),
    Column("files", JSON, nullable=False),
    Column("sha256", String(64), nullable=False),
    Column("image_digest", String(80), nullable=False),
    Column("created_at", Float, nullable=False),
    Column("expires_at", Float, nullable=False),
)
exec_requests = Table(
    "factory_exec_requests",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("task_id", ForeignKey("runtime_tasks.id"), nullable=False),
    Column("plan_id", ForeignKey(exec_plans.c.id), nullable=False),
    Column("call_key", String(64), nullable=False),
    Column("creator_role", String(100), nullable=False),
    Column("binding", JSON, nullable=False),
    Column("sha256", String(64), nullable=False),
    Column("created_at", Float, nullable=False),
    Column("expires_at", Float, nullable=False),
    UniqueConstraint("task_id", "call_key"),
)
exec_decisions = Table(
    "factory_exec_decisions",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("request_id", ForeignKey(exec_requests.c.id), nullable=False, unique=True),
    Column("reviewer_role", String(63), nullable=False),
    Column("decision", String(10), nullable=False),
    Column("binding_sha256", String(64), nullable=False),
    Column("created_at", Float, nullable=False),
    Column("expires_at", Float, nullable=False),
)
exec_revocations = Table(
    "factory_exec_revocations",
    metadata,
    Column("request_id", ForeignKey(exec_requests.c.id), primary_key=True),
    Column("reviewer_role", String(63), nullable=False),
    Column("created_at", Float, nullable=False),
)
exec_jobs = Table(
    "factory_exec_jobs",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("task_id", ForeignKey("runtime_tasks.id"), nullable=False),
    Column("step_id", ForeignKey("runtime_steps.id"), nullable=False, unique=True),
    Column("request_id", ForeignKey(exec_requests.c.id), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("creator_role", String(100), nullable=False),
    Column("binding_sha256", String(64), nullable=False),
    Column("state", String(20), nullable=False),
    Column("attempts", Integer, nullable=False, default=0),
    Column("created_at", Float, nullable=False),
    Column("lease_token", String(36)),
    Column("lease_until", Float),
    Column("result", JSON),
    Column("result_sha256", String(64)),
    Column("executor_role", String(63)),
)

registry_roles = Table(
    "factory_registry_roles",
    metadata,
    Column("db_role", String(63), primary_key=True),
    Column("principal", String(80), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("enabled", String(3), nullable=False),
)
signing_keys = Table(
    "factory_signing_keys",
    metadata,
    Column("id", String(64), primary_key=True),
    Column("tenant", String(100), nullable=False),
    Column("signer_role", String(63), nullable=False),
    Column("public_key_hex", String(64), nullable=False),
    Column("not_before", Float, nullable=False),
    Column("expires_at", Float, nullable=False),
    Column("state", String(10), nullable=False),
)
signed_artifacts = Table(
    "factory_signed_artifacts",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("bundle_id", ForeignKey(bundles.c.id), nullable=False),
    Column("job_id", ForeignKey(exec_jobs.c.id), nullable=False),
    Column("key_id", ForeignKey(signing_keys.c.id), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("tenant", String(100), nullable=False),
    Column("signer_role", String(63), nullable=False),
    Column("stage", String(20), nullable=False),
    Column("envelope", JSON, nullable=False),
    Column("sha256", String(64), nullable=False),
    Column("created_at", Float, nullable=False),
    Column("expires_at", Float, nullable=False),
    UniqueConstraint("job_id", "key_id"),
    CheckConstraint("stage='EVIDENCE_ONLY'", name="ck_factory_signed_evidence_only"),
)
